// ========================================
// 상세페이지 표시 기능
// ========================================

// URL에서 작업물 ID 확인
const params = new URLSearchParams(window.location.search);
const workId = params.get("id");

// 등록된 작업물 가져오기
const workKeys = Object.keys(works);
const work = works[workId];

// HTML 요소
const titleEl = document.getElementById("workTitle");
const categoryEl = document.getElementById("workCategory");
const subtitleEl = document.getElementById("workSubtitle");
const galleryEl = document.getElementById("workGallery");
const nextEl = document.getElementById("nextWork");

if (work) {

  titleEl.textContent = work.title;
  categoryEl.textContent = work.category;
  subtitleEl.textContent = work.subtitle;

  document.title = `${work.title} | SION.JIN`;

  // 등록한 이미지 출력
  work.images.forEach((src, index) => {

    const img = document.createElement("img");

    img.src = src;
    img.alt = `${work.title} 작업 이미지 ${index + 1}`;
    img.loading = index === 0 ? "eager" : "lazy";
    img.decoding = "async";

    // 이미지 경로 오류 확인
    img.onerror = () => {
      console.error("이미지를 불러올 수 없습니다:", src);
    };

    galleryEl.appendChild(img);
  });

  // 다음 작업물
  const currentIndex = workKeys.indexOf(workId);
  const nextIndex = (currentIndex + 1) % workKeys.length;

  nextEl.href = `./work-view.html?id=${workKeys[nextIndex]}`;

} else {

  titleEl.textContent = "작업물을 찾을 수 없습니다.";
  nextEl.hidden = true;

}
